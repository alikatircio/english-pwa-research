import { fileURLToPath } from 'node:url';
import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
import { VitePWA } from 'vite-plugin-pwa';

// GitHub Pages serves the app from /<repo-name>/; CI may override via BASE_PATH.
const base = process.env.BASE_PATH ?? '/english-pwa-research/';

const path = (p: string) => fileURLToPath(new URL(p, import.meta.url));

// --- PWA (07 §6.1) ----------------------------------------------------------
// Same value as `--bg` in src/ui/styles/tokens.css (light theme): calm neutral.
const BG_COLOR = '#f6f5f1';

const pwa = VitePWA({
  // 'prompt': a new SW waits; src/pwa/registerSW.ts applies it only on Home,
  // never mid-session (02 §3, 07 §6.2). Registration is done by that module.
  registerType: 'prompt',
  injectRegister: false,
  // The SW is only exercised with `vite build && vite preview`.
  devOptions: { enabled: false },
  // public/icons/* is already matched by globPatterns; avoid duplicate precache entries.
  includeManifestIcons: false,
  manifest: {
    id: base,
    name: 'İngilizce Üretim',
    short_name: 'Üretim',
    description: 'Türkçe durumdan İngilizce cümle üretme alıştırması.',
    lang: 'tr',
    dir: 'ltr',
    start_url: base,
    scope: base,
    display: 'standalone',
    orientation: 'portrait',
    theme_color: BG_COLOR,
    background_color: BG_COLOR,
    icons: [
      { src: 'icons/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
      { src: 'icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
      { src: 'icons/icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
    ],
  },
  workbox: {
    // Content JSON is bundled into the JS, so app code and content always ship together.
    globPatterns: ['**/*.{js,css,html,svg,png,json,woff2}'],
    navigateFallback: 'index.html',
    cleanupOutdatedCaches: true,
    // Off on purpose: the waiting SW is activated by registerSW.ts at a safe moment.
    skipWaiting: false,
    clientsClaim: false,
  },
});

export default defineConfig(({ mode }) => ({
  base,
  plugins: [react(), pwa],
  // Agent worktrees under .claude/ must not trigger dev-server reloads.
  server: { watch: { ignored: ['**/.claude/**'] } },
  resolve: {
    alias: {
      // Content bundle: generated by `npm run content:build`; e2e builds use a fixed fixture
      // so content edits never break the e2e suite (07 §4).
      '@content': mode === 'e2e' ? path('./content/fixtures/e2e-items.json') : path('./src/content/items.json'),
    },
  },
}));
